"""Regenerates docs/SCAM_PATTERNS.md and docs/MODEL_CARD.md from the rule pack and the measured metrics.

Run after changing data/scam_patterns.yaml or retraining:
    python -m app.classifier      # retrain, writes data/model_metrics.json
    python -m app.docs_gen
"""

import json
from pathlib import Path

from .classifier import FAMILIES, METRICS_PATH, PACK, SCAM_TYPES

DOCS = Path(__file__).resolve().parents[2] / "docs"


def _cell(s) -> str:
    return str(s or "").replace("|", "\\|").replace("\n", " ")


def scam_patterns() -> str:
    lines = [
        "# Scam patterns (rule pack)",
        "",
        f"Rule pack version **{PACK['version']}**, last reviewed {PACK['last_reviewed']}. Source of truth: "
        "[`backend/data/scam_patterns.yaml`](../backend/data/scam_patterns.yaml). This file is generated by "
        "`python -m app.docs_gen`; do not edit it by hand.",
        "",
        "**Confidence:** `verified` = stated on an official or primary page; `reported` = from reliable media or a "
        "search summary, still to be confirmed on the primary page; `unverified` = added by the team, confirm before "
        "relying on it. The sources were located on 20 Nov 2026 by web search. **Before the final submission, the "
        "team must open every link and confirm the wording.**",
        "",
        "## How the verdict is decided",
        "",
        "1. **Normalise** the text (full-width to normal, zero-width characters removed, `s a f e` collapsed, "
        "`hxxp` and `[.]` undone). Highlights still map back to what the customer pasted.",
        "2. **Entity checks** on links (shorteners, bare IP addresses, punycode, look-alike or org-name-in-domain), "
        "the sender number and name the customer typed, and the channel (a bank or SingPost SMS with a link).",
        "3. **Playbook rules** below. Protective wording is skipped: a rule with `unless_before` ignores a match "
        "such as \"never share your OTP\".",
        "4. **Model** (TF-IDF + calibrated logistic regression) gives a probability. It can raise caution but can "
        "never produce \"Likely scam\" on its own.",
        "",
        "**Likely scam** needs a *critical* rule, or a strong rule plus a second signal family, or "
        "three families (model ≥ 0.5), or any rule with model ≥ 0.85. One weak signal never does it. "
        "**Zero trust:** a message that *asks you to act* (pay, click, log in, share a code; the `asks_action` rule) is never shown as \"No known signs\", because AI writes fluent messages and a message can't prove who sent it. That request is not a scam sign, so it never counts towards \"Likely scam\". "
        "**Not sure** is shown when the model is between 0.4 and 0.6 and no strong rule fired (and, with no rule "
        "at all, up to 0.9). **No known signs** never means safe: the result always says what we can't tell.",
        "",
        "## Signal families",
        "",
        "| Family | Meaning |",
        "|---|---|",
        *[f"| `{k}` | {_cell(v)} |" for k, v in FAMILIES.items()],
        "",
        "## Scam types and advice",
        "",
        "| Scam type | What we tell the customer to do | Source |",
        "|---|---|---|",
    ]
    for k, v in SCAM_TYPES.items():
        src = f"[{_cell(v['source'])}]({v['source_url']})" if v.get("source_url") else _cell(v.get("source"))
        lines.append(f"| **{_cell(v['label'])}** (`{k}`) | {'<br>'.join(_cell(a) for a in v['advice'])} | {src} |")
    lines += ["", "## Patterns", "",
              "| id | Family | Scam type | Critical | Weight | What it explains | Source | Date | Confidence |",
              "|---|---|---|---|---|---|---|---|---|"]
    for p in PACK["patterns"]:
        src = f"[{_cell(p.get('source'))}]({p['source_url']})" if p.get("source_url") else _cell(p.get("source"))
        lines.append(f"| `{p['id']}` | {p['family']} | {p.get('scam_type') or 'cross-cutting'} | {'yes' if p.get('critical') else ''} "
                     f"| {p.get('weight', 1)} | {_cell(p['explanation'])} | {src} | {p.get('source_date', '')} | {p.get('confidence', '')} |")
    lines += ["", "## Checks in code (not in the YAML)", "",
              "| id | What it checks | Source |", "|---|---|---|",
              "| `short_link` | Link uses a URL shortener (list in `official_domains.yaml`) | GovTech TechNews, 30 Jul 2024 |",
              "| `lookalike_link` | Bare IP, punycode, an organisation's name inside a domain it does not own, or within edit distance 2 of an official domain | GovTech TechNews, 30 Jul 2024 |",
              "| `bank_sms_link` (critical) | Source is SMS, the message claims to be a bank or SingPost, and it has a link | MAS and ABS, 19 Jan 2022; GovTech TechNews, 30 Jul 2024 |",
              "| `foreign_sender` | Typed sender number has a non-+65 country code while claiming a Singapore organisation (+65 is not proof of anything) | GovTech TechNews, 30 Jul 2024 (+63 example) |",
              "| `sender_name_mismatch` | Typed sender name such as \"Singapore Post\" instead of \"SingPost\" | GovTech TechNews, 30 Jul 2024 |",
              "| `email_domain_mismatch` | Typed email address does not end in the claimed organisation's domain | ScamShield |",
              "", "## Languages", "",
              "Keywords exist in English (with Singlish), Simplified Chinese and Malay for the main patterns. Tamil is "
              "covered by the model only (training rows are machine-assisted and marked for native-speaker review); no "
              "Tamil keyword is used in a rule until a native speaker has checked it.", ""]
    return "\n".join(lines)


def model_card() -> str:
    m = json.loads(METRICS_PATH.read_text())
    g, u = m["grouped_by_template"], m["unseen_tactics"]
    gc, uc = g["checker"], u["checker"]

    def row(name, d):
        return (f"| {name} | {d['accuracy']} | {d['precision_scam']} | {d['recall_scam']} | {d['f1_scam']} | "
                f"{d['false_positive_rate']} |")

    def cm(d):
        c = d["confusion_matrix"]
        return (f"| | Predicted legit | Predicted scam |\n|---|---|---|\n| **Legit** | {c['true_legit']} | {c['false_scam']} |\n"
                f"| **Scam** | {c['missed_scam']} | {c['caught_scam']} |")

    def ok(v, target, higher=True):
        return "met" if (v >= target if higher else v <= target) else "**not met**"

    lines = [
        "# Model card: \"Is this real?\" message checker",
        "",
        "Generated by `python -m app.docs_gen` from `backend/data/model_metrics.json` (written by "
        "`python -m app.classifier`). Rule pack version " + m.get("rule_pack_version", "?") + ".",
        "",
        "## What it is",
        "",
        "- **Rules first.** A researched rule pack ([SCAM_PATTERNS.md](SCAM_PATTERNS.md)) explains every flag.",
        "- **Model second.** TF-IDF on word 1-2-grams and character 2-5-grams, then logistic regression wrapped in "
        "`CalibratedClassifierCV` (sigmoid, 5-fold) so the probability means something. It runs on our own "
        "backend only; no third-party API or LLM sees the message, and links are never opened.",
        "- **The model never decides alone.** With no rule fired it can show \"Be careful\" (≥ 0.9) or \"Not sure\" "
        "(0.4-0.9), never \"Likely scam\". If the model file is missing or broken, the checker runs on rules only "
        "and says \"Not sure\" unless a rule fired.",
        "",
        "## Data",
        "",
        f"- `backend/data/messages.csv`: **{m['n_total']} synthetic messages**, generated by "
        "`data/generate_messages.py` (fixed seed). 11 scam types, at least 46 rows each; about 54% legitimate, "
        "including 500+ **hard negatives** (real-style bank OTP notices that say \"never share\", SingPost notices "
        "without links, friends borrowing money without pressure, real job interviews, shop promotions, police "
        "advisories, very short replies). About 61% English with Singlish, 18% Chinese, 13% Malay, 5% Tamil "
        "(machine-assisted, needs native review), 3% code-mixed. Every name, number and domain is made up.",
        f"- `backend/data/unseen_tactics.csv`: **{u['n']} hand-written messages** with new wording, obfuscation and "
        "mixed language. Never used for training or for tuning the model.",
        "",
        "## Results",
        "",
        "### What customers see (rules + model). Targets apply here.",
        "",
        "\"Flagged\" = the customer sees *Likely scam* or *Be careful*.",
        "",
        "| Test set | Scams flagged (recall) | Legit shown *Likely scam* | Hard negatives shown *Likely scam* | Legit shown *Be careful* | Scams shown *Likely scam* |",
        "|---|---|---|---|---|---|",
        f"| Template families held out (n = {g['n_test']}) | {gc['recall_scam']} | {gc['legit_shown_likely_scam']} | "
        f"{gc['hard_negative_shown_likely_scam']} | {gc['legit_shown_be_careful']} | {gc['scam_shown_likely_scam']} |",
        f"| Unseen tactics (n = {u['n']}) | {uc['recall_scam']} | {uc['legit_shown_likely_scam']} | "
        f"{uc['hard_negative_shown_likely_scam']} | {uc['legit_shown_be_careful']} | {uc['scam_shown_likely_scam']} |",
        "",
        "| Target | Held-out families | Unseen tactics |",
        "|---|---|---|",
        f"| Scam recall ≥ 0.90 | {ok(gc['recall_scam'], 0.9)} | {ok(uc['recall_scam'], 0.9)} |",
        f"| False-positive rate ≤ 0.05 (legit shown *Likely scam*) | {ok(gc['legit_shown_likely_scam'], 0.05, False)} | {ok(uc['legit_shown_likely_scam'], 0.05, False)} |",
        f"| Hard-negative false-positive rate ≤ 0.10 (shown *Likely scam*) | {ok(gc['hard_negative_shown_likely_scam'], 0.10, False)} | {ok(uc['hard_negative_shown_likely_scam'], 0.10, False)} |",
        "",
        f"Honest caveat: on held-out template families, **{gc['legit_shown_be_careful']:.0%} of genuine messages "
        f"still get \"Be careful\"** (hard negatives flagged at either level: {gc['hard_negative_flagged']:.0%}). "
        "We count that as a false positive in the recall/precision table below. \"Be careful\" asks the customer "
        "to check through an official channel; it never blocks anything.",
        "",
        "### Detection scores",
        "",
        "| Split | Accuracy | Scam precision | Scam recall | Scam F1 | False-positive rate |",
        "|---|---|---|---|---|---|",
        row("Checker, template families held out", gc),
        row("Checker, unseen tactics", uc),
        row("Model only, template families held out", g),
        row("Model only, unseen tactics", u["model_only"]),
        row("Model only, random 25% split (optimistic: near-duplicates on both sides)", m),
        "",
        f"Model only on held-out families: hard-negative false-positive rate **{g['hard_negative_false_positive_rate']}** "
        f"(n = {g['n_hard_negatives']}). This is why the model never decides alone.",
        "",
        "### Recall by scam type (model only, template families held out)",
        "",
        "Precision per type is not defined for a scam/legit classifier (a legit message has no type); overall "
        "precision is in the table above.",
        "",
        "| Scam type | n | Recall |",
        "|---|---|---|",
        *[f"| {k} | {v['n']} | {v['recall']} |" for k, v in g["recall_by_scam_type"].items()],
        "",
        "### Confusion matrices",
        "",
        "Checker, template families held out:",
        "",
        cm(gc),
        "",
        "Checker, unseen tactics:",
        "",
        cm(uc),
        "",
        "### Calibration (model only, template families held out)",
        "",
        f"Brier score **{g['calibration']['brier']}** (0 is perfect, 0.25 is a coin flip).",
        "",
        "| Predicted probability | n | Mean predicted | Share that were scams |",
        "|---|---|---|---|",
        *[f"| {b['bin']} | {b['n']} | {b['mean_predicted']} | {b['share_scam']} |" for b in g["calibration"]["bins"]],
        "",
        "## How the unseen set was used",
        "",
        "The unseen-tactics set was never used to train or tune the model. It **was** looked at once while building "
        "the rules, and it exposed five general rule bugs that were fixed: \"PayNow\" matching the word \"now\", "
        "\"No code needed\" matching \"no COD\", a police advisory (\"officials will never ask you to hand over "
        "valuables\") firing the cash-handover rule, \"mom\"/\"MAS\" being treated as a claim to be the government, "
        "and the model alone being able to say \"Likely scam\". So the unseen scores are slightly optimistic; the "
        "held-out template-family scores are the fairer number.",
        "",
        "## Known misses (kept, not patched)",
        "",
        "- A business-email message that says \"all future payments should be made to the account below\" "
        "(unseen tactics). We did **not** add a rule for that exact wording after seeing the test set, because "
        "that would make the unseen score meaningless.",
        "",
        "## Limits",
        "",
        "- **Synthetic, template-generated data.** English-heavy. Not tested on real customer messages; real-world "
        "accuracy is unknown.",
        "- Tamil rows are machine-assisted and not reviewed by a native speaker.",
        "- We cannot see who really sent a message, and we never open links, so a well-written scam with no link, "
        "no payment request and no pressure can pass as \"No known signs\".",
        "- **Not a replacement for ScamShield** (app, or Helpline 1799).",
        "- The model is **never retrained automatically**. Staff can mark reported messages as training candidates; "
        "they are exported to CSV for offline review by people first.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    DOCS.mkdir(exist_ok=True)
    (DOCS / "SCAM_PATTERNS.md").write_text(scam_patterns(), encoding="utf-8")
    (DOCS / "MODEL_CARD.md").write_text(model_card(), encoding="utf-8")
    print(f"wrote {DOCS / 'SCAM_PATTERNS.md'} and {DOCS / 'MODEL_CARD.md'}")
